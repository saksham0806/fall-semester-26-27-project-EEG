"""Assemble REPORT.md from results/*.json — metd_plan.md §10, §11 Reporting.

Generated, never hand-edited. Sections whose inputs are missing are listed as not run
rather than omitted, so the report says what has not happened as clearly as what has.

    python -m arch_metd.eval.report
"""
import json

from ..contract import ROOT

RESULTS = ROOT / "arch_metd/results"
OUT = ROOT / "arch_metd/REPORT.md"


def _load(name):
    p = RESULTS / name
    return json.loads(p.read_text()) if p.exists() else None


def _auc_row(r):
    if "p_value" in r:
        return f"{r['proportion']:.4f} ({r['n_higher']}/{r['n']}, p={r['p_value']:.4f})"
    if "ci_lo" in r:
        flag = " ⚠️ crosses chance" if r.get("crosses_chance") else ""
        return f"{r['auc']:.4f} [{r['ci_lo']:.3f}, {r['ci_hi']:.3f}] n={r['n']}{flag}"
    return f"{r['auc']:.4f} n={r['n']}"


def build():
    L = ["# METD — results", "",
         "Generated by `python -m arch_metd.eval.report`. Do not hand-edit.", ""]

    info, base = _load("build_info.json"), _load("baselines.json")
    if base:
        L += ["## Baselines (§8.3, recomputed from the built arrays)", "",
              "Every headline number is quoted against these. None is hardcoded.", "",
              "| baseline | value |", "|---|---:|",
              f"| corpus dummy, 3-class (knowing only the corpus) | **{base['corpus_dummy_3class']:.4f}** |",
              f"| majority class, 3-class | {base['majority_3class']:.4f} |",
              f"| majority domain | {base['majority_domain']:.4f} |",
              f"| depression majority (n={base['y_dep']['n']}) | {base['y_dep']['majority']:.4f} |",
              f"| stress majority (n={base['y_str']['n']}) | {base['y_str']['majority']:.4f} |", ""]
    if info:
        L += [f"Arrays: fingerprint `{info['fingerprint']}`, {info['n_segments']} segments, "
              f"K={info['var_gate_k']}.", ""]

    L += ["## Within-corpus cross-validation (§7)", "",
          "Segment-level figures in `cv*.json` are **not** primary (§12 item 7). These are "
          "aggregated to the unit the label varies over, by logit median.", ""]
    modes = {m: _load(f"aggregate{'' if m == 'main' else '_' + m}.json")
             for m in ("main", "lambda0", "randbb", "permuted")}
    if modes["main"]:
        keys = list(modes["main"])
        L += ["| metric | main | λ=0 | random backbone | permuted |", "|---|---|---|---|---|"]
        for k in keys:
            L.append("| " + k + " | " + " | ".join(
                _auc_row(modes[m][k]) if modes.get(m) and k in modes[m] else "—"
                for m in ("main", "lambda0", "randbb", "permuted")) + " |")
        L += ["", "`permuted` must collapse to chance; `random backbone` separates a learned "
              "representation from an input artifact; `λ=0` is the method-off control "
              "without which \"adaptation helped\" is unfalsifiable.", ""]
    else:
        L += ["*not run*", ""]

    pr = _load("probes.json")
    L += ["## Frozen domain probes (§8.1) and the gate (§8.2 → §6.5 item 4)", ""]
    if pr:
        L += [f"Targets: balanced chance {pr['chance_balanced']:.3f}, "
              f"majority domain {pr['majority_domain']:.4f}.", "",
              "| mode | anchor probe | full-set probe | silhouette |", "|---|---:|---:|---:|"]
        for m, r in pr["modes"].items():
            L.append(f"| {m} | {r['anchor_probe']:.4f} | {r['full_probe']:.4f} | "
                     f"{r['silhouette']:+.4f} |")
        g = pr["gate"]
        L += ["", f"**Gate: {'PASS' if g['passes'] else 'FAIL'}** — criterion pre-registered "
              f"in `results/preregistration.md` before measurement.", "",
              "The adversary's own head accuracy is never a probe (§12 item 9).", ""]
    else:
        L += ["*not run*", ""]

    ch = _load("crosshead.json")
    L += ["## Cross-head extrapolation (§8.4)", ""]
    if ch:
        L += ["Compared against in-domain positives from the same head, never against zero.", "",
              "| head | in-domain pos | in-domain neg | separation | out-of-domain | verdict |",
              "|---|---:|---:|---:|---:|---|"]
        for head, r in ch.items():
            L.append(f"| {head} | {r['in-domain positive']['median']:.3f} | "
                     f"{r['in-domain negative']['median']:.3f} | "
                     f"{r['in-domain separation']:+.3f} | "
                     f"{r['out-of-domain (unsupervised)']['median']:.3f} | {r['verdict']} |")
        L += ["", "No cross-head argmax at inference (§9): the heads train on disjoint data "
              "and their outputs share no scale.", ""]
    else:
        L += ["*not run*", ""]

    tr = _load("transfer.json")
    L += ["## Cross-corpus transfer (§6.2, §7.5)", "",
          "Within-corpus CV measures decodability only — corpus identity is present in the "
          "test fold too. Only transfer tests whether the representation survives a "
          "hardware change.", ""]
    if tr:
        L += ["| run | mode | adversary | λ@stop | n train | n test |",
              "|---|---|---|---:|---:|---:|"]
        for r in tr["runs"]:
            L.append(f"| {r['transfer']} | {r['mode']} | "
                     f"{'on' if r['adversary_operative'] else '**off** (1 train corpus)'} | "
                     f"{r['lambda_at_stop']:.3f} | {r['n_train']} | {r['n_test']} |")
        L += ["", "⚠️ **Three of the four directions train on a single corpus**, so the "
              "adversary has nothing to align against and is disabled at source. Only "
              "`stress_sam40cog_to_eegmat` can test domain adaptation at all.", ""]
    else:
        L += ["*not run*", ""]

    L += ["## Known confounds", "",
          "- **Mumtaz is confounded with its acquisition setup** — EDF channel count predicts "
          "diagnosis at 0.8889 (baseline 0.5238). Full detail in `results/mumtaz_audit.md`. "
          "Quote no Mumtaz depression figure without it.",
          "- **CogLoad carries ~8x EEGMAT's above-45 Hz power** after gating (29x before). "
          "No filter reaches it; see the rejection table.",
          "- **Every CV number here is subject-disjoint but never device-disjoint.** The "
          "transfer rows are the only device-disjoint measurements.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    OUT.write_text(build())
    print(f"wrote {OUT}")
