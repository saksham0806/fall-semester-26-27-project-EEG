def _load(name):
    p = RESULTS / name
    return json.loads(p.read_text()) if p.exists() else None


def _mcnemar_eegmat():
    """§7.3 arms are paired on the same held-out subjects, so the contrast is McNemar."""
    import numpy as np
    from scipy.stats import binomtest

    from .aggregate import by_unit

    def pairs(tag):
        f = RESULTS / f"preds_transfer_{tag}.npz"
        if not f.exists():
            return None
        d = dict(np.load(f))
        m = (d["y_domain"] == 4) & (d["y_str"] != -1)
        if not m.any():
            return None
        ids, s, y = by_unit(d["trial_id"][m], d["str"][m], d["y_str"][m])
        sub = np.array([i.rsplit("_", 1)[0] for i in ids])
        out = {}
        for u in np.unique(sub):
            t, b = s[(sub == u) & (y == 1)], s[(sub == u) & (y == 0)]
            if len(t) and len(b):
                out[u] = bool(t[0] > b[0])
        return out

    a = pairs("stress_sam40cog_to_eegmat")
    b = pairs("stress_sam40cog_to_eegmat_lambda0_locked") or \
        pairs("stress_sam40cog_to_eegmat_lambda0")
    if not a or not b:
        return None
    subs = sorted(set(a) & set(b))
    n01 = sum(1 for u in subs if not a[u] and b[u])
    n10 = sum(1 for u in subs if a[u] and not b[u])
    k1 = sum(a[u] for u in subs)
    k0 = sum(b[u] for u in subs)
    return {"n": len(subs), "n01": n01, "n10": n10, "k1": k1, "k0": k0,
            "p": float(binomtest(n10, n01 + n10, 0.5).pvalue) if n01 + n10 else float("nan"),
            "p1": float(binomtest(k1, len(subs), 0.5).pvalue),
            "p0": float(binomtest(k0, len(subs), 0.5).pvalue)}


def _auc_row(r):
    if "p_value" in r:
        return f"{r['proportion']:.4f} ({r['n_higher']}/{r['n']}, p={r['p_value']:.4f})"
    if "ci_lo" in r:
        flag = " ⚠️ crosses chance" if r.get("crosses_chance") else ""
        return f"{r['auc']:.4f} [{r['ci_lo']:.3f}, {r['ci_hi']:.3f}] n={r['n']}{flag}"
    return f"{r['auc']:.4f} n={r['n']}"


