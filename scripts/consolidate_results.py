"""
Phase 3.3 — collect every cross-validated result into one ranked comparison.

Results are spread across two JSON schemas (Results/phase1/, Results/phase2/) plus
report.md, which is a *different protocol* (single 70/10/20 split) and is therefore
excluded from the ranking rather than merged into it. Mixing a single-split number
into a cross-validated table is exactly the error that made deep models look 0.21 AUC
better than they are.

Every row below is 5-fold subject-grouped CV. Stress uses within-subject AUC on SAM40;
depression uses subject-level AUC over all 53 MODMA subjects.

Run:  .venv/bin/python scripts/consolidate_results.py
"""
import json
import os

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
R1 = os.path.join(PROJECT_ROOT, "Results", "phase1")
R2 = os.path.join(PROJECT_ROOT, "Results", "phase2")
OUT = os.path.join(PROJECT_ROOT, "Results", "SUMMARY.md")


def load(path):
    try:
        with open(path) as f:
            return json.load(f)
    except FileNotFoundError:
        return None


def collect():
    """-> list of (task, model, score, std_or_None, source, note)."""
    rows = []

    if (d := load(os.path.join(R1, "sam40_ceiling.json"))):
        for m, r in d.items():
            lo, hi = r["auc_within_subject"]
            rows.append(("stress", m, lo, hi, "phase1/sam40_ceiling", "SAM40 only"))

    if (d := load(os.path.join(R1, "corpus_ablation.json"))):
        for m, combos in d.items():
            for label, r in combos.items():
                if label == "SAM40 only":
                    continue  # already covered by sam40_ceiling
                lo, hi = r["auc_within"]
                rows.append(("stress", m, lo, hi, "phase1/corpus_ablation", label))

    if (d := load(os.path.join(R1, "depression_cv.json"))):
        for m, r in d.items():
            rows.append(("depression", m, r["subject_level"]["auc"], None,
                         "phase1/depression_cv", f"{r['subject_level']['n_subjects']} subjects OOF"))

    if (d := load(os.path.join(R2, "riemannian.json"))):
        for label in ("SAM40 only", "SAM40 + CogLoad"):
            if label in d:
                lo, hi = d[label]["auc_within"]
                rows.append(("stress", "Riemannian tangent space", lo, hi,
                             "phase2/riemannian", label))
        if "depression" in d:
            rows.append(("depression", "Riemannian tangent space",
                         d["depression"]["auc_subject"], None, "phase2/riemannian",
                         "global re-centering"))

    if (d := load(os.path.join(R2, "cbramod_probe.json"))):
        for tag, r in d.items():
            lo, hi = r["auc_within"]
            rows.append(("stress", f"CBraMod ({tag})", lo, hi, "phase2/cbramod_probe",
                         "frozen probe, SAM40"))

    if (d := load(os.path.join(R2, "ssl_pretrain.json"))):
        for tag, r in d.items():
            lo, hi = r["auc_within"]
            rows.append(("stress", f"SSL masked-recon ({tag})", lo, hi,
                         "phase2/ssl_pretrain", "frozen probe, SAM40"))

    if (d := load(os.path.join(R2, "channel_density.json"))):
        for ch, r in d.items():
            rows.append(("depression", f"Riemannian @ {ch}ch", r["auc_subject"], None,
                         "phase2/channel_density", f"{r['tangent_dims']} dims"))

    return rows


def table(rows, task):
    sel = sorted([r for r in rows if r[0] == task], key=lambda r: -r[2])
    metric = "within-subject AUC" if task == "stress" else "subject-level AUC"
    out = [f"\n## {task.capitalize()} — ranked by {metric}\n",
           "| # | Model | AUC | Config | Source |",
           "| :-- | :--- | :--- | :--- | :--- |"]
    for i, (_, m, s, sd, src, note) in enumerate(sel, 1):
        val = f"**{s:.4f}**" if i == 1 else f"{s:.4f}"
        if sd is not None:
            val += f" ±{sd:.3f}"
        out.append(f"| {i} | {m} | {val} | {note} | `{src}` |")
    return "\n".join(out), sel


def main():
    rows = collect()
    if not rows:
        print("No result artifacts found — run the phase1/phase2 scripts first.")
        return

    body = ["# Consolidated Results",
            "",
            "Auto-generated by `scripts/consolidate_results.py`. Every row is **5-fold "
            "subject-grouped CV** with zero subject leakage.",
            "",
            "`report.md` is deliberately **excluded**: it is a single 70/10/20 split, a "
            "different protocol, and its deep-model figures run ~0.21 AUC high. Do not "
            "merge those numbers into this table."]

    for task in ("stress", "depression"):
        t, sel = table(rows, task)
        body.append(t)
        if sel:
            best = sel[0]
            body.append(f"\nBest: **{best[1]}** at {best[2]:.4f} ({best[5]}).")

    body += ["", "## Controls", "",
             "Learned-representation results carry random-init controls, which is what makes "
             "them measurements rather than assertions:", "",
             "- CBraMod pretrained vs random init — pretraining **helps** (+0.076) yet still "
             "loses to a 105-dim linear model by 0.18.",
             "- SSL pretrained vs random init — pretraining **hurts** (−0.050).", ""]

    text = "\n".join(body) + "\n"
    with open(OUT, "w") as f:
        f.write(text)
    print(text)
    print(f"written: {OUT}")


if __name__ == "__main__":
    main()
