"""
Collect every all3 result into two tables that must be read together.

Track A — within-corpus. Strips the free corpus split out entirely. This is the only measure
of what a model learned about mental state, and the only one worth optimising.

Track B — pooled, with attribution. The headline 3-class number, always next to the 0.6267
corpus-ID shortcut, plus the signature delta where a signature-preserving and a
signature-removed variant of the same model both exist. That delta IS the amplifier's
contribution (measured at +0.18 for the Riemannian pair).

GENERATED FILE — re-run after any new experiment or it silently goes stale.
scripts/consolidate_results.py reads only Results/phase1/ and phase2/ and will never pick
this up; Results/SUMMARY.md contains no all3 row.

Run:  .venv/bin/python scripts/all3_tracks.py
"""
import glob
import json
import os

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RES = os.path.join(PROJECT_ROOT, "Results", "all3")
CORPORA = ("MODMA", "SAM40", "CogLoad")

# Signature-preserving -> signature-removed pairs. The gap is what the amplifier was worth.
SIGNATURE_PAIRS = [
    ("F1 early fusion (global)", "F1 early fusion (per-corpus)"),
    ("DANN TSception alpha=0.0", "DANN TSception alpha=1.0"),
    ("DANN EEGTransformer alpha=0.0", "DANN EEGTransformer alpha=1.0"),
]


def load_all():
    """Every model dict across every result file, keyed by name."""
    models, shortcut = {}, None
    for path in sorted(glob.glob(os.path.join(RES, "*.json"))):
        with open(path) as f:
            blob = json.load(f)
        shortcut = blob.get("shortcut_baseline", shortcut)
        src = os.path.basename(path)
        for name, v in blob.items():
            if isinstance(v, dict) and "accuracy" in v:
                models[name] = {**v, "source": src}
    return models, shortcut


def fmt(v, n=4):
    return "—" if v is None else f"{v:.{n}f}"


def main():
    models, shortcut = load_all()
    if not models:
        raise SystemExit(f"no results in {RES} — run the all3 scripts first")

    # Majority baselines are a property of the data, identical in every result file.
    any_model = next(iter(models.values()))
    base = {c: any_model["within_corpus"][c]["majority_within"]
            for c in CORPORA if c in any_model.get("within_corpus", {})}

    L = []
    L.append("# all3 — dual-track results\n")
    L.append("GENERATED by `scripts/all3_tracks.py`. Re-run after any new experiment.\n")
    L.append(f"{len(models)} models. Corpus-ID shortcut (zero EEG understanding): "
             f"**{fmt(shortcut)}**.\n")

    # --- Track A ------------------------------------------------------------------
    L.append("\n## Track A — within-corpus (the honest measure)\n")
    L.append("Accuracy inside each corpus, next to that corpus's majority baseline. "
             "A negative margin means the model is worse than a constant predictor.\n")
    L.append("Sorted by CogLoad, the open problem: no model has ever beaten its 0.6886 "
             "majority.\n")

    head = "| model | source | " + " | ".join(f"{c} | Δ" for c in CORPORA) + " | macro-F1 |"
    L.append(head)
    L.append("|---" * (3 + 2 * len(CORPORA)) + "|")
    L.append("| **majority baseline** | — | " +
             " | ".join(f"**{fmt(base.get(c))}** | —" for c in CORPORA) + " | — |")

    def cogload(kv):
        w = kv[1].get("within_corpus", {}).get("CogLoad")
        return -(w["accuracy"] if w else -1)

    for name, v in sorted(models.items(), key=cogload):
        w = v.get("within_corpus", {})
        cells = []
        for c in CORPORA:
            if c in w:
                mark = "**" if w[c]["accuracy"] > base.get(c, 1.0) else ""
                cells.append(f"{mark}{fmt(w[c]['accuracy'])}{mark} | {w[c].get('margin', 0):+.3f}")
            else:
                cells.append("— | —")
        L.append(f"| {name} | {v['source']} | " + " | ".join(cells) +
                 f" | {fmt(v.get('macro_f1'))} |")

    # --- Track B ------------------------------------------------------------------
    L.append("\n## Track B — pooled, with attribution\n")
    L.append("Pooled 3-class accuracy is **not** interpretable on its own — it includes the "
             "free corpus split. Read the margin, never the accuracy.\n")

    L.append("| model | source | accuracy | vs 0.6267 | balanced | macro-F1 | domain acc | sec |")
    L.append("|---|---|---|---|---|---|---|---|")
    for name, v in sorted(models.items(), key=lambda kv: -kv[1]["accuracy"]):
        L.append(f"| {name} | {v['source']} | {fmt(v['accuracy'])} | {v['margin']:+.4f} "
                 f"| {fmt(v.get('balanced_accuracy'))} | {fmt(v.get('macro_f1'))} "
                 f"| {fmt(v.get('domain_accuracy'))} | {fmt(v.get('elapsed_sec'), 0)} |")

    # --- signature attribution -----------------------------------------------------
    deltas = [(keep, drop, models[keep]["accuracy"] - models[drop]["accuracy"])
              for keep, drop in SIGNATURE_PAIRS if keep in models and drop in models]
    if deltas:
        L.append("\n### Signature delta — how much was the amplifier\n")
        L.append("Same model, signature preserved vs removed. The gap is the device's "
                 "contribution to the pooled number.\n")
        L.append("| signature kept | signature removed | delta |")
        L.append("|---|---|---|")
        for keep, drop, d in deltas:
            L.append(f"| {keep} ({fmt(models[keep]['accuracy'])}) "
                     f"| {drop} ({fmt(models[drop]['accuracy'])}) | **{d:+.4f}** |")

    # --- verdict -------------------------------------------------------------------
    winners = [n for n, v in models.items()
               if (w := v.get("within_corpus", {}).get("CogLoad"))
               and w["accuracy"] > base.get("CogLoad", 1.0)]
    L.append("\n## Verdict\n")
    if winners:
        L.append(f"**{len(winners)} model(s) beat the CogLoad majority**: "
                 + ", ".join(f"`{w}`" for w in winners) + ".")
    else:
        L.append("**No model beats the CogLoad within-corpus majority of "
                 f"{fmt(base.get('CogLoad'))}.** Every corpus contains at most two of the "
                 "three classes, so the 3-class framing gives the model a task no corpus can "
                 "supervise. This is a data-collection blocker, not a modelling one — the "
                 "same data as two binary tasks reaches 0.7716 and 0.7560 AUC.")

    out = os.path.join(RES, "TRACKS.md")
    with open(out, "w") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\nwritten: {out}")


if __name__ == "__main__":
    main()
